#!/usr/bin/env node

'use strict';

// Tests for local WAT->wasm repair. Modeled on the real asunder.co finding — a
// 2.1 MB `bower_solver_bg.*.wasm` that the capture stored as WAT text. Both
// jsmap paths that touched it concluded "corrupt, re-download from the origin"
// when the module was complete and assemblable offline.

const assert = require('node:assert');
const { looksLikeWat, assembleWat, hasWasmMagic } = require('./lib/wat-repair.cjs');
const { detectStub, urlForStub } = require('./repair-capture-stubs.cjs');

let passed = 0;
function test(name, fn) { fn(); passed += 1; console.log(`  ok - ${name}`); }
const async_tests = [];
function atest(name, fn) { async_tests.push([name, fn]); }

const MINIMAL_WAT = '(module (func $add (param i32 i32) (result i32) local.get 0 local.get 1 i32.add) (export "add" (func $add)))';

test('recognizes WAT text', () => {
  assert.equal(looksLikeWat(Buffer.from(MINIMAL_WAT)), true);
  assert.equal(looksLikeWat(Buffer.from('   \n  (module)')), true);
});

test('recognizes WAT behind leading comments', () => {
  assert.equal(looksLikeWat(Buffer.from(';; generated by wasm2wat\n(module)')), true);
  assert.equal(looksLikeWat(Buffer.from('(; block comment ;)\n(module)')), true);
});

test('does not mistake a wasm binary or arbitrary bytes for WAT', () => {
  assert.equal(looksLikeWat(Buffer.from([0x00, 0x61, 0x73, 0x6d, 1, 0, 0, 0])), false);
  assert.equal(looksLikeWat(Buffer.from('No Content: https://x/y.wasm')), false);
  assert.equal(looksLikeWat(Buffer.from('<!doctype html><html></html>')), false);
  // `(module` must be the first token, not merely present somewhere
  assert.equal(looksLikeWat(Buffer.from('console.log("(module")')), false);
});

test('a .wasm stored as WAT is flagged as locally repairable, not as a stub to refetch', () => {
  const d = detectStub('solver_bg.wasm', Buffer.from(MINIMAL_WAT));
  assert.equal(d.reason, 'wasm-as-wat-text');
  assert.equal(d.repair, 'local-wat-assembly');
  // it must never be handed to the backfill fetcher
  assert.equal(urlForStub({ ...d, file: 'solver_bg.wasm' }, 'https://example.test'), null);
});

test('genuine stubs still route to refetch', () => {
  const s = detectStub('kernel.wasm', Buffer.from('No Content: https://x/kernel.wasm'));
  assert.equal(s.reason, 'no-content-placeholder');
  assert.equal(urlForStub({ ...s, file: 'kernel.wasm' }, 'https://example.test'), 'https://x/kernel.wasm');
  // and non-WAT garbage is still wrong-magic-bytes
  assert.equal(detectStub('kernel.wasm', Buffer.from('total garbage')).reason, 'wrong-magic-bytes');
  // a real binary is not a stub at all
  assert.equal(detectStub('kernel.wasm', Buffer.from([0x00, 0x61, 0x73, 0x6d, 1, 0, 0, 0])).isStub, false);
});

atest('assembles plain WAT into a valid wasm binary', async () => {
  const result = await assembleWat(MINIMAL_WAT, 'minimal.wat');
  assert.equal(result.ok, true, `expected assembly to succeed: ${result.reason}`);
  assert.equal(hasWasmMagic(result.bytes), true);
  assert.deepEqual(result.normalizations, []);
  const instance = new WebAssembly.Instance(new WebAssembly.Module(result.bytes));
  assert.equal(instance.exports.add(2, 3), 5);
});

atest('applies a recorded normalization only when the verbatim parse fails', async () => {
  // `(ref func)` in an elem segment is a dialect wabt's parser rejects. The
  // captured asunder.co solver is written this way.
  const dialect = '(module (func $f) (table $t 1 1 funcref) (elem $e (i32.const 0) (ref func) (ref.func $f)))';
  const result = await assembleWat(dialect, 'dialect.wat');
  assert.equal(result.ok, true, `expected assembly to succeed: ${result.reason}`);
  assert.equal(hasWasmMagic(result.bytes), true);
  assert.deepEqual(result.normalizations, ['elem-reftype-to-funcref']);
});

atest('reports a reason rather than throwing on genuinely broken WAT', async () => {
  const result = await assembleWat('(module (func $x (this is not wat', 'broken.wat');
  assert.equal(result.ok, false);
  assert.equal(typeof result.reason, 'string');
  assert.ok(result.reason.length > 0);
});

(async () => {
  for (const [name, fn] of async_tests) { await fn(); passed += 1; console.log(`  ok - ${name}`); }
  console.log(`\n${passed} passed`);
})().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
